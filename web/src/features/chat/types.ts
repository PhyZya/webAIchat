import type { ErrorCode, Role } from '@filament/shared';

/**
 * Состояние одной реплики.
 *
 * Отдельные значения для «остановлено» и «сломалось» нужны не для красоты:
 * задание требует, чтобы после остановки уже полученный кусок остался в истории,
 * а по виду сообщения было понятно, что ответ неполный и почему.
 */
export type TurnStatus =
  /** Запрос ушёл, первый токен ещё не пришёл. */
  | 'pending'
  /** Текст идёт прямо сейчас. */
  | 'streaming'
  /** Модель договорила. */
  | 'done'
  /** Прервано человеком. */
  | 'stopped'
  /** Прервано ошибкой. */
  | 'failed';

export type Turn = {
  id: string;
  role: Role;
  content: string;
  status: TurnStatus;
  /** Заполняется только у status === 'failed'. */
  errorCode?: ErrorCode;
  /** Через сколько секунд имеет смысл повторить, если сервис попросил подождать. */
  retryAfterSec?: number;
};
